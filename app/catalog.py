def seed(db, demo=False):
    """Insert built-in templates once; demo price list only in demo mode."""
    from local import now
    with db.tx() as c:
        for i, (tid, cat, title, body) in enumerate(DOCS):
            c.execute("""INSERT OR IGNORE INTO templates(id, kind, category, title, body, builtin, sort, updated_at)
                         VALUES(?,?,?,?,?,1,?,?)""", ("doc_" + tid, "document", cat, title, body.strip(), i, now()))
        for field, phrases in PHRASES.items():
            for i, ph in enumerate(phrases):
                c.execute("""INSERT OR IGNORE INTO templates(id, kind, category, title, body, builtin, sort, updated_at)
                             VALUES(?,?,?,?,?,1,?,?)""", (f"ph_{field}_{i}", "phrase", field, ph[:60], ph, i, now()))
        for i, (tid, spec, title, fields, diag, tooth, rx) in enumerate(EXAMS):
            body = json.dumps({"fields": fields, "diagnoses": diag, "tooth": tooth, "rx": rx}, ensure_ascii=False)
            c.execute("""INSERT OR IGNORE INTO templates(id, kind, category, title, body, builtin, sort, updated_at)
                         VALUES(?,?,?,?,?,1,?,?)""", ("ex_" + tid, "exam", spec, title, body, i, now()))
        for i, (name, dose, how, days) in enumerate(DRUGS):
            body = json.dumps({"name": name, "dose": dose, "how": how, "days": days}, ensure_ascii=False)
            c.execute("""INSERT OR IGNORE INTO templates(id, kind, category, title, body, builtin, sort, updated_at)
                         VALUES(?,?,?,?,?,1,?,?)""", (f"drug_{i}", "drug", "", name, body, i, now()))
        if demo:
            for i, (code, title, price, cat) in enumerate(DEMO_SERVICES):
                c.execute("INSERT OR IGNORE INTO services VALUES(?,?,?,?,?,?,1)", (f"demo_{i}", code, title, price, cat, "demo"))


def builtin_document(tid):
    for t, cat, title, body in DOCS:
        if "doc_" + t == tid:
            return {"category": cat, "title": title, "body": body.strip()}
    return None
